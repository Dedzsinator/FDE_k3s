_helm_up() {
  local release="$1" chart="$2"; shift 2
  local status
  status=$(helm status "${release}" -n "${NS}" -o json 2>/dev/null | jq -r '.info.status' 2>/dev/null || echo "")
  if [[ "$status" == "deployed" ]]; then
    skip "${release}"
  else
    if [[ -n "$status" ]]; then
      info "Removing previous '${status}' release: ${release}"
      helm uninstall "${release}" -n "${NS}" >>"$LOG" 2>&1 || true
      sleep 5
    fi
    # Build subchart dependencies (loki-stack, kube-prometheus-stack, etc.) if needed
    if grep -q '^dependencies:' "${CHARTS_DIR}/${chart}/Chart.yaml" 2>/dev/null; then
      _spin_start "Building chart dependencies for ${chart}"
      helm dependency build "${CHARTS_DIR}/${chart}" >>"$LOG" 2>&1 \
        && _spin_stop "Dependencies ready" \
        || { _spin_stop "dep build"; warn "helm dependency build failed for ${chart} — continuing"; }
    fi
    run "Deploying ${release}" helm upgrade --install "${release}" "${CHARTS_DIR}/${chart}" \
      --namespace "${NS}" "$@"
    # Wait separately so a slow image pull warns instead of aborting the installer
    local _wl
    _wl=$(kubectl get deploy,sts -n "${NS}" \
      -l "app.kubernetes.io/instance=${release}" -o name 2>/dev/null | head -1 || true)
    if [[ -n "${_wl:-}" ]]; then
      _spin_start "Waiting for ${release}"
      kubectl rollout status "${_wl}" -n "${NS}" --timeout=15m >>"$LOG" 2>&1 \
        && _spin_stop "${release} ready" \
        || { _spin_stop "${release}"; warn "${release} not ready in 15m — check: kubectl get pods -n ${NS}"; }
    fi
  fi
}

