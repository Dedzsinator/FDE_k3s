# ══════════════════════════════════════════════════════════════════════════════
#  ENTRY POINT
# ══════════════════════════════════════════════════════════════════════════════
show_banner
: > "$LOG"

if ! $CLI_MODE && [[ -t 0 && -t 1 ]]; then
  if ! command -v whiptail &>/dev/null; then
    printf "  ${Y}⚠${N}  whiptail not found — installing it first...\n"
    apt-get install -y -qq whiptail 2>/dev/null || true
  fi
  if command -v whiptail &>/dev/null; then
    run_tui_wizard
  else
    warn "Could not install whiptail. Falling back to CLI mode."
    [[ -z "$NODE_IP" ]] && err "--ip is required.  Usage: sudo ./install.sh --ip <IP>"
  fi
else
  [[ -z "$NODE_IP" && "$DEPLOY_MODE" != "worker" ]] && \
    err "--ip is required in CLI mode.  Usage: sudo ./install.sh --ip <IP>"
fi

# ── Print resolved configuration ──────────────────────────────────────────────
printf "  ${D}Mode      :${N} ${W}%s${N}\n"  "$DEPLOY_MODE"
printf "  ${D}Node IP   :${N} ${W}%s${N}\n"  "$NODE_IP"
printf "  ${D}Hostname  :${N} ${W}%s${N}\n"  "$NODE_HOSTNAME"
printf "  ${D}Domain    :${N} ${W}%s${N}\n"  "$DOMAIN"
printf "  ${D}Namespace :${N} ${W}%s${N}\n"  "$NS"
printf "  ${D}Log       :${N} ${W}%s${N}\n"  "$LOG"
$DRY_RUN && printf "\n  ${Y}⚠  DRY-RUN mode — no changes will be made${N}\n"
printf "\n"
[[ $EUID -ne 0 ]] && err "Must run as root:  sudo ./install.sh"

# ══════════════════════════════════════════════════════════════════════════════
#  WORKER-ONLY PATH
# ══════════════════════════════════════════════════════════════════════════════
if [[ "$DEPLOY_MODE" == "worker" ]]; then
  phase "System prerequisites"
  run "apt update" apt-get update -qq
  run "Install curl" apt-get install -y -qq curl

  phase "Join cluster"
  [[ -z "$JOIN_URL"   ]] && err "--join-url required for worker mode"
  [[ -z "$JOIN_TOKEN" ]] && err "--join-token required for worker mode"
  if command -v k3s &>/dev/null; then
    skip "k3s already installed"
  else
    _spin_start "Joining cluster at ${JOIN_URL} (tier=${WORKER_TIER})"
    maybe curl -sfL https://get.k3s.io | INSTALL_K3S_EXEC="agent \
      --server ${JOIN_URL} --token ${JOIN_TOKEN} \
      --node-label uns.fde/tier=${WORKER_TIER}" sh - >>"$LOG" 2>&1
    _spin_stop "k3s agent joined"
  fi
  printf "\n${P}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${N}\n"
  printf "${W} Worker joined!  Tier: %s${N}\n" "$WORKER_TIER"
  printf "${P}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${N}\n\n"
  printf "  Verify on control-plane:  ${W}kubectl get nodes -L uns.fde/tier${N}\n\n"
  exit 0
fi

# ══════════════════════════════════════════════════════════════════════════════
#  PHASE 1 — System prerequisites
# ══════════════════════════════════════════════════════════════════════════════
phase "System prerequisites"

step "Set hostname to ${NODE_HOSTNAME}"
if [[ "$(hostname)" != "${NODE_HOSTNAME}" ]]; then
  maybe hostnamectl set-hostname "${NODE_HOSTNAME}"
  ok "Hostname → ${NODE_HOSTNAME}"
else skip "Hostname already ${NODE_HOSTNAME}"; fi

step "Install OS packages"
