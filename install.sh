WT_BT="  FDE Platform Installer v${INSTALLER_VERSION}  ·  Accenture Factory Digital Edge  "

auto_detect_ip() {
  ip route get 1.1.1.1 2>/dev/null | awk '/src/{print $7}' | head -1 \
    || hostname -I 2>/dev/null | awk '{print $1}' \
    || echo "0.0.0.0"
}

wt_welcome() {
  whiptail --backtitle "$WT_BT" --title " Welcome " --msgbox \
"FDE Platform Installer  v${INSTALLER_VERSION}

This wizard configures and autonomously deploys the full
Factory Digital Edge stack on this machine.

  • Idempotent — safe to re-run on existing nodes
  • All components deployed via Helm + kubectl
  • Supports single-node, control-plane, or worker join

Requirements:
  • Ubuntu 22.04 / 24.04 / 26.04  (x86_64 or ARM64)
  • Run as root (sudo ./install.sh)
  • Internet access for package downloads

Press  Enter  to begin." 18 62
}

wt_mode() {
  DEPLOY_MODE=$(whiptail --backtitle "$WT_BT" --title " Deployment Mode " --nocancel \
    --menu "\nHow will this node be used?" 15 68 3 \
    "single"          "Full stack on this machine  (recommended)" \
    "control-plane"   "k3s master + stack; print worker join token" \
    "worker"          "Join an existing FDE cluster (k3s agent only)" \
    3>&1 1>&2 2>&3)
}

wt_network() {
  local detected; detected="$(auto_detect_ip)"
  local out
  out=$(whiptail --backtitle "$WT_BT" --title " Network Configuration " --nocancel \
    --form "\nConfigure this node's network identity:" 17 68 6 \
    "Node IP address  :" 1 1 "${NODE_IP:-$detected}" 1 21 38 64 \
    "Hostname         :" 2 1 "$NODE_HOSTNAME"         2 21 28 64 \
    "Ingress domain   :" 3 1 "$DOMAIN"               3 21 38 64 \
    "Site tag (short) :" 4 1 "$SITE"                 4 21 18 32 \
    "vLLM URL  (opt.) :" 5 1 "$VLLM_URL"             5 21 38 128 \
    "Obsidian URL(opt):" 6 1 "$OBS_URL"              6 21 38 128 \
    3>&1 1>&2 2>&3) || return 0
  mapfile -t _f <<< "$out"
  NODE_IP="${_f[0]}"; NODE_HOSTNAME="${_f[1]}"; DOMAIN="${_f[2]}"
  SITE="${_f[3]}"; VLLM_URL="${_f[4]}"; OBS_URL="${_f[5]}"
  [[ -z "$NODE_IP" ]] && { whiptail --backtitle "$WT_BT" --msgbox "Node IP cannot be empty." 8 40; wt_network; }
}

