run_tui_wizard() {
  wt_welcome
  wt_mode
  if [[ "$DEPLOY_MODE" == "worker" ]]; then
    wt_network   # still need IP for output
    wt_worker
    wt_confirm
  else
    wt_network
    wt_services
    wt_passwords
