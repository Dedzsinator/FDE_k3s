# ── Banner ────────────────────────────────────────────────────────────────────
show_banner() {
  clear
  # Top arm: P (purple). Bottom arm: L (lavender), exact mirror of top.
  printf '%s' "${P}"
  printf '%s\n' \
    ' *#' \
    ' #****##' \
    ' #*********#' \
    ' #************#**' \
    ' #******************#' \
    '     #*****************#*#' \
    '         *#*****************##' \
    '              #******************#' \
    '                  #****************#' \
    '                      ###**********#'
  # TIP — P→L colour transition mid-line
  printf '%s%s\n' '                       #%%' "${L}##*******##"
  # Bottom arm: exact mirror of top arm (lines 10→1), in L colour
  printf '%s\n' \
    '                      ###**********#' \
    '                  #****************#' \
    '              #******************#' \
    '         *#*****************##' \
    '     #*****************#*#' \
    ' #******************#' \
    ' #************#**' \
    ' #*********#' \
    ' #****##' \
    ' *#'
  printf '%s\n' "${N}"
  printf "        ${W}Factory Digital Edge${N}  ${D}·${N}  ${P}Accenture${N}\n"
  printf "        ${D}Full K8s Stack Installer  v%s${N}\n" "$INSTALLER_VERSION"
