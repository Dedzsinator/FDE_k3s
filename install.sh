}

# ── Logging ───────────────────────────────────────────────────────────────────
STEP=0; PHASE_NUM=0
phase()  { PHASE_NUM=$((PHASE_NUM+1)); printf "\n${P}━━━ PHASE %d: %s ${N}\n" "$PHASE_NUM" "$1"; }
step()   { STEP=$((STEP+1)); printf "  ${W}[%d]${N} %s\n" "$STEP" "$1"; }
ok()     { printf "      ${G}✔${N}  %s\n" "$1"; }
warn()   { printf "      ${Y}⚠${N}  %s\n" "$1"; }
err()    { printf "      ${R}✘${N}  %s\n" "$1" >&2; exit 1; }
info()   { printf "      ${D}→${N}  %s\n" "$1"; }
skip()   { printf "      ${D}↷${N}  %s\n" "$1 (already deployed — skipping)"; }

_spin_pid=""
_spin_start() {
  printf "      ${D}⟳${N}  %s..." "$1"
  ( while true; do
      for c in '⠋' '⠙' '⠹' '⠸' '⠼' '⠴' '⠦' '⠧' '⠇' '⠏'; do
        printf "\r      ${P}%s${N}  %s..." "$c" "$1"; sleep 0.08
      done
    done ) &
  _spin_pid=$!; disown "$_spin_pid" 2>/dev/null || true
}
_spin_stop() {
  [[ -n "${_spin_pid:-}" ]] && kill "$_spin_pid" 2>/dev/null || true; _spin_pid=""
  printf "\r      ${G}✔${N}  %-60s\n" "$1"
}
_spin_fail() {
  [[ -n "${_spin_pid:-}" ]] && kill "$_spin_pid" 2>/dev/null || true; _spin_pid=""
  printf "\r      ${R}✘${N}  FAILED — see %s\n" "$LOG"
  tail -20 "$LOG"; exit 1
}
run() {
  local msg="$1"; shift
  _spin_start "$msg"
  if "$@" >>"$LOG" 2>&1; then _spin_stop "$msg"; else _spin_fail; fi
}

